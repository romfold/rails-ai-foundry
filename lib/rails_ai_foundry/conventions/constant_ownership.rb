# frozen_string_literal: true

require 'active_support/inflector'
require_relative 'files'

module RailsAIFoundry
  module Conventions
    class ConstantOwnership
      def initialize(root, pack)
        @files = Files.new(root)
        @pack = pack
      end

      def check!(constants, receipt:)
        owners.each do |path, claimed|
          next if path == receipt

          conflict = (constants & claimed).first
          next unless conflict

          raise InstallationError, "#{conflict} is already generated by #{path}. " \
                                   'Choose another name or review the existing component before changing its role.'
        end
      end

      private

      def owners
        component_owners.merge(agent_owners)
      end

      def component_owners
        receipts('components').to_h do |path|
          [path, [@files.yaml(path).fetch('constant')]]
        end
      end

      def agent_owners
        receipts('agents').to_h do |path|
          namespace = @files.yaml(path).fetch('namespace')
          name = File.basename(path, '.yml').camelize
          [path, %w[Agent Tool Schema].map { |suffix| "#{namespace}::#{name}#{suffix}" }]
        end
      end

      def receipts(category)
        directory = "#{@pack}/.foundry/#{category}"
        Dir.glob('**/*.yml', base: @files.path(directory)).sort.map { |path| "#{directory}/#{path}" }
      end
    end
  end
end
